dialogues = []

def reg(did, level, title, topic, lines_raw, question, answer, alts=None):
    parsed = []
    for l in lines_raw:
        parts = [x.strip() for x in l.split("|")]
        assert len(parts) == 3, f"Bad line format in {did}: {l}"
        parsed.append({"speaker": parts[0], "bg": parts[1], "ru": parts[2]})
    assert len(parsed) >= 4, f"Fewer than 4 lines in {did}"
    assert any(answer in p["bg"] for p in parsed), f"Answer '{answer}' not in {did}"
    dialogues.append({
        "id": did,
        "level": level,
        "title": title,
        "topic": topic,
        "lines": parsed,
        "question": question,
        "answer": answer,
        "alternatives": alts or []
    })

