const grammarSource = "https://beron.mon.bg/";
const make = (
  id: string,
  level: Level,
  title: string,
  rule: string,
  formation: string,
  contrast: string,
  lines: string,
  practice: string,
  type: Task["type"] = "gap",
): LessonUnit => ({
  id,
  level,
  title,
  rule,
  formation,
  contrast,
  source: [
    "present",
    "aorist",
    "imperfect",
    "perfect",
    "pluperfect",
    "future",
    "future-past",
    "future-perfect",
    "future-perfect-past",
  ].includes(id)
    ? "https://ibl.bas.bg/wp-content/uploads/2020/08/Todor_Lazarov_Disertatsiya.pdf"
    : grammarSource,
  examples: lines
    .split("\n")
    .filter(Boolean)
    .map((l) => {
      const [bg, ru] = l.split("|");
      return { bg, ru };
    }),
  tasks: practice
    .split("\n")
    .filter(Boolean)
    .map((l, i) => {
      const [prompt, answer, explanation, options] = l.split("|");
      return {
        id: `unit-${id}-${i}`,
        type,
        prompt,
        answers: answer.split(" / "),
        explanation,
        options: options?.split(" / "),
        skill: title,
        level,
      };
    }),
});
