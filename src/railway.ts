const originalRailTerms: RailTerm[] = Object.entries(groups).flatMap(
  ([topic, text]) =>
    text.split("\n").map((line, i) => {
      const [bg, ru] = line.split("|");
      return {
        id: "rail-" + topic + "-" + i,
        bg,
        ru,
        topic,
        source:
          topic === "Движение и инфраструктура"
            ? railSources.bdz
            : railSources.tsi,
      };
    }),
);
const existingRailLabels = new Set(originalRailTerms.map(t => t.bg));
const firstMerge = [...originalRailTerms, ...extraRailTerms.filter(t => !existingRailLabels.has(t.bg))];
const firstLabels = new Set(firstMerge.map(t => t.bg.toLowerCase()));
const seenBatch2 = new Set<string>();
const mergedRailTerms = [...firstMerge, ...extraRailTerms2.filter(t => {
  const key = t.bg.toLowerCase();
  if (firstLabels.has(key) || seenBatch2.has(key)) return false;
  seenBatch2.add(key);
  return true;
})];
const mergedLabels = new Set(mergedRailTerms.map(t => t.bg.toLowerCase()));
export const railTerms: RailTerm[] = [...mergedRailTerms, ...engineeringLabels.filter(t => !mergedLabels.has(t.bg.toLowerCase()))];
